function normalize(ch: string) {
  if (ch === "ß" || ch === "ẞ") return "ß";
  const upper = ch.toUpperCase();
  if (upper === "Ä" || upper === "Ö" || upper === "Ü") return upper;
  return GLYPHS[upper] ? upper : "?";
}

export function pixelWidth(text: string, scale: number, tracking = 1) {
  let n = 0;
  for (const ch of text) n += (normalize(ch) === " " ? 3 : 6) * scale + tracking;
  return Math.max(0, n - tracking);
}

export function pixelLines(text: string, maxW: number, scale: number, tracking = 1): string[] {
  const out: string[] = [];
  for (const para of text.split("\n")) {
    let line = "";
    for (const word of para.split(/\s+/)) {
      const test = line ? `${line} ${word}` : word;
      if (line && pixelWidth(test, scale, tracking) > maxW) {
        out.push(line);
        line = word;
      } else line = test;
    }
    if (line) out.push(line);
  }
  return out;
}

export function drawPixelText(c: C, text: string, x: number, y: number, scale: number, color: string, tracking = 1) {
  c.fillStyle = color;
  let px = x;
  for (const raw of text) {
    const ch = normalize(raw);
    const glyph = GLYPHS[ch];
    const adv = (ch === " " ? 3 : 6) * scale + tracking;
    if (!glyph) {
      px += adv;
      continue;
    }
    for (let row = 0; row < glyph.length; row++) {
      const bits = glyph[row];
      for (let col = 0; col < bits.length; col++) {
        if (bits[col] === "1") c.fillRect(px + col * scale, y + row * scale, scale, scale);
      }
    }
    px += adv;
  }
}

export function drawPixelTextCenter(c: C, text: string, cx: number, y: number, scale: number, color: string, tracking = 1) {
  drawPixelText(c, text, cx - pixelWidth(text, scale, tracking) / 2, y, scale, color, tracking);
}